window.PAMRA_LANG = (() => {
  const KEY = 'pamra_lang';
  function get() { return localStorage.getItem(KEY) || 'en'; }
  function set(lang) {
    localStorage.setItem(KEY, lang);
    apply();
  }
  function t(key) {
    const entry = window.I18N[key];
    if (!entry) return key;
    return entry[get()] || entry.en;
  }
  function apply() {
    const lang = get();
    document.documentElement.lang = lang;
    document.body.classList.toggle('lang-ur', lang === 'ur');
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    // Update toggle UI
    document.querySelectorAll('.lang-toggle [data-lang]').forEach(el => {
      el.classList.toggle('active', el.dataset.lang === lang);
    });
  }
  return { get, set, t, apply };
})();
